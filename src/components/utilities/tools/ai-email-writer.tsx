"use client";

import { Mail } from "lucide-react";
import { useState, type FormEvent } from "react";
import { composeEmail, type EmailTone, type EmailType } from "@/lib/text-tools";
import { cn } from "@/lib/utils";
import {
  ClearButton,
  CopyButton,
  ExampleChips,
  FieldLabel,
  inputClass,
  ModeNotice,
  OutputReveal,
  PrimaryAction,
  textareaClass,
  ToolPanel,
} from "../tool-ui";
import type { ToolProps } from "./types";

const TYPES: { id: EmailType; label: string }[] = [
  { id: "follow-up", label: "Follow-up" },
  { id: "meeting-request", label: "Meeting request" },
  { id: "thank-you", label: "Thank you" },
  { id: "introduction", label: "Introduction" },
  { id: "request", label: "Request" },
  { id: "apology", label: "Apology" },
];
const TONES: EmailTone[] = ["formal", "friendly", "concise"];

export default function AiEmailWriter({ examples }: ToolProps) {
  const [type, setType] = useState<EmailType>("follow-up");
  const [tone, setTone] = useState<EmailTone>("friendly");
  const [recipient, setRecipient] = useState("");
  const [sender, setSender] = useState("");
  const [topic, setTopic] = useState("");
  const [points, setPoints] = useState("");
  const [email, setEmail] = useState<{ subject: string; body: string } | null>(null);
  const [runId, setRunId] = useState(0);

  const generate = (event?: FormEvent) => {
    event?.preventDefault();
    setEmail(composeEmail({ type, tone, recipient, sender, topic, points: points.split("\n") }));
    setRunId((n) => n + 1);
  };

  const clear = () => {
    setRecipient("");
    setSender("");
    setTopic("");
    setPoints("");
    setEmail(null);
  };

  const fullText = email ? `Subject: ${email.subject}\n\n${email.body}` : "";

  return (
    <div className="space-y-5">
      <ModeNotice tone="demo">
        <strong>Template mode.</strong> Drafts are assembled from professionally written templates, not generated by AI. An AI option will
        be added — and clearly labelled — once an API is connected.
      </ModeNotice>
      <ExampleChips
        examples={examples}
        onSelect={(v) => {
          setPoints(v);
          if (!topic) setTopic(v.split("\n")[0]?.toLowerCase() ?? "");
        }}
      />
      <div className="grid gap-5 lg:grid-cols-2">
        <ToolPanel title="Email details" actions={<ClearButton onClick={clear} disabled={!recipient && !sender && !topic && !points} />}>
          <form onSubmit={generate} className="space-y-4 p-5">
            <fieldset>
              <legend className="mb-2 text-sm font-medium text-foreground">Email type</legend>
              <div className="grid grid-cols-2 gap-2 sm:grid-cols-3">
                {TYPES.map((t) => (
                  <button
                    key={t.id}
                    type="button"
                    aria-pressed={type === t.id}
                    onClick={() => setType(t.id)}
                    className={cn(
                      "rounded-xl border px-3 py-2 text-sm transition-colors",
                      type === t.id ? "border-primary bg-primary-soft font-medium text-primary" : "border-border text-foreground hover:border-primary/40",
                    )}
                  >
                    {t.label}
                  </button>
                ))}
              </div>
            </fieldset>
            <div className="grid gap-4 sm:grid-cols-2">
              <div>
                <FieldLabel htmlFor="email-recipient">Recipient name</FieldLabel>
                <input id="email-recipient" value={recipient} onChange={(e) => setRecipient(e.target.value)} placeholder="e.g. Sam" className={inputClass} />
              </div>
              <div>
                <FieldLabel htmlFor="email-sender">Your name</FieldLabel>
                <input id="email-sender" value={sender} onChange={(e) => setSender(e.target.value)} placeholder="e.g. Alex" className={inputClass} />
              </div>
            </div>
            <div>
              <FieldLabel htmlFor="email-topic">Topic</FieldLabel>
              <input id="email-topic" value={topic} onChange={(e) => setTopic(e.target.value)} placeholder="e.g. the product demo on Tuesday" className={inputClass} />
            </div>
            <div>
              <FieldLabel htmlFor="email-points" hint="One per line">
                Key points
              </FieldLabel>
              <textarea id="email-points" value={points} onChange={(e) => setPoints(e.target.value)} rows={4} placeholder={"Share the pricing overview\nPropose a call next week"} className={textareaClass} />
            </div>
            <fieldset>
              <legend className="mb-2 text-sm font-medium text-foreground">Tone</legend>
              <div className="flex gap-2">
                {TONES.map((t) => (
                  <button
                    key={t}
                    type="button"
                    aria-pressed={tone === t}
                    onClick={() => setTone(t)}
                    className={cn(
                      "flex-1 rounded-xl border px-3 py-2 text-sm capitalize transition-colors",
                      tone === t ? "border-primary bg-primary-soft font-medium text-primary" : "border-border text-foreground hover:border-primary/40",
                    )}
                  >
                    {t}
                  </button>
                ))}
              </div>
            </fieldset>
            <PrimaryAction type="submit">Generate draft</PrimaryAction>
          </form>
        </ToolPanel>
        <ToolPanel title="Draft" actions={<CopyButton text={fullText} />}>
          {email ? (
            <OutputReveal id={runId}>
              <div className="p-5">
                <p className="text-xs font-medium uppercase tracking-wide text-muted-foreground">Subject</p>
                <p className="mt-1 font-medium text-foreground">{email.subject}</p>
                <hr className="my-4 border-border" />
                <pre className="whitespace-pre-wrap font-sans text-[0.95rem] leading-relaxed text-foreground">{email.body}</pre>
              </div>
            </OutputReveal>
          ) : (
            <div className="flex min-h-72 flex-col items-center justify-center p-5 text-center text-sm text-muted-foreground">
              <Mail className="mb-3 h-8 w-8 opacity-40" aria-hidden="true" />
              Fill in the details and generate a draft.
            </div>
          )}
        </ToolPanel>
      </div>
    </div>
  );
}
